/* Helper: get product by ID */
PD.getProduct = function(id) {
  return PD.catalog.find(function(p) { return p.id === id; });
};

/* Helper: get products by category */
PD.getByCategory = function(category) {
  return PD.catalog.filter(function(p) { return p.category === category; });
};

/* Helper: get products by routine role */
PD.getByRole = function(role) {
  return PD.catalog.filter(function(p) { return p.routineRole === role; });
};

/* Helper: render a product card HTML */
PD.renderCard = function(p, delay, idx) {
  var delayClass = delay ? ' reveal-delay-' + delay : '';
  // Primeros 4 cards (above-fold) = eager + high priority; resto = lazy
  var isAboveFold = (typeof idx === 'number' && idx < 4);
  var loadingAttr = isAboveFold ? 'eager' : 'lazy';
  var priorityAttr = isAboveFold ? ' fetchpriority="high"' : '';
  // Solo activar hover swap si img1 !== img2 (evita re-fetch innecesario)
  var hoverSwap = (p.img2 && p.img2 !== p.img1)
    ? ' onmouseover="this.src=\'' + p.img2 + '\'" onmouseout="this.src=\'' + p.img1 + '\'"'
    : '';
  var imgHtml = p.img1
    ? '<img src="' + p.img1 + '" alt="' + p.name + '"' + hoverSwap +
      ' loading="' + loadingAttr + '"' + priorityAttr + ' decoding="async" width="800" height="1000">'
    : '';
  return '<a href="producto.html?id=' + p.id + '" class="product-card reveal' + delayClass + '">' +
    '<div class="product-card-img">' +
      imgHtml +
      '<div class="pills"><span class="pill pill--cacao">' + p.pill + '</span>' +
      (p.category === 'Protección Solar' ? '<span class="pill pill--ocre">FPS 50+</span>' : '') +
      '</div>' +
    '</div>' +
    '<div class="product-card-body">' +
      '<p class="product-card-category">' + p.category.toUpperCase() + '</p>' +
      '<h3 class="product-card-name">' + p.name + '</h3>' +
      '<div class="product-card-price">' +
        '<span class="current">$' + p.price + '</span>' +
        '<span class="compare">$' + p.comparePrice + '</span>' +
        '<span class="discount">' + p.discount + '</span>' +
      '</div>' +
      '<div class="product-card-rating">' +
        '<span class="stars" style="color:var(--ocre)">' + p.stars + ' ★</span>' +
        '<span class="score" style="font-size:12px;opacity:0.5;">(' + p.reviews + ' reseñas)</span>' +
      '</div>' +
      '<button class="product-card-btn" ' +
        'data-add-to-cart ' +
        'data-product-id="' + p.id + '" ' +
        'data-product-name="' + p.name + '" ' +
        'data-product-price="' + p.price + '"' +
      '>AGREGAR</button>' +
    '</div>' +
  '</a>';
};

